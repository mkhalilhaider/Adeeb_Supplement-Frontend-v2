/** "  lahore " → "Lahore" for a listed city; otherwise the tidied text as typed. */
export function canonicalCity(input) {
  const text = String(input ?? "")
    .trim()
    .replace(/\s+/g, " ");
  return PK_CITIES.find((c) => c.toLowerCase() === text.toLowerCase()) ?? text;
}
